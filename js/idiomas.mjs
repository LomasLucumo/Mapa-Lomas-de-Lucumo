export function normalizarIdioma(idioma) {
  return ['es', 'en', 'zh-Hans'].includes(idioma) ? idioma : 'es';
}

export function obtenerTexto(texto, idioma) {
  if (!texto || !texto.trim()) return 'Contenido no disponible';
  const elegido = normalizarIdioma(idioma);
  if (elegido === 'es') return texto;
  if (catalogo[texto]?.[elegido]) return catalogo[texto][elegido];
  const patrones = [
    [/^(\d+) de (\d+) visitadas$/, ['{1} of {2} visited', '已到访 {1}/{2}']],
    [/^(\d+) de (\d+)$/, ['{1} of {2}', '{1} / {2}']],
    [/^(\d+) km · (\d+) paradas$/, ['{1} km · {2} stops', '{1} 公里 · {2} 站']],
    [/^Circuito (.+) · (\d+) km$/, ['{1} route · {2} km', '{1} · {2} 公里']],
    [/^(.+) · (\d+) km$/, ['{1} · {2} km', '{1} · {2} 公里']],
    [/^Circuito (.+)$/, ['{1} route', '{1}路线']],
    [/^Parada (\d+): (.+)$/, ['Stop {1}: {2}', '站点 {1}：{2}']],
    [/^Marcaste (.+) como visitada$/, ['Marked {1} as visited', '已将 {1} 标记为到访']],
    [/^Has llegado a (.+)$/, ['You have arrived at {1}', '您已到达 {1}']],
    [/^Continúas en (.+)$/, ['Continue at {1}', '从 {1} 继续']],
    [/^(.+) ya está completado$/, ['{1} is already completed', '{1}已完成']],
    [/^Completaste el Circuito (.+)\.$/, ['You completed the {1} route.', '您已完成{1}路线。']],
    [/^Distancia restante: (.+)$/, ['Remaining distance: {1}', '剩余距离：{1}']],
    [/^A (.+) por el sendero$/, ['{1} along the trail', '沿步道还有 {1}']],
    [/^¿Reiniciar el recorrido del Circuito (.+)\? Se borrarán las paradas visitadas\.$/, ['Restart the {1} route? Visited stops will be cleared.', '重新开始{1}路线？已到访的站点将被清除。']],
  ];
  for (const [patron, traducciones] of patrones) {
    const coincidencia = texto.match(patron);
    if (coincidencia) return traducciones[elegido === 'en' ? 0 : 1].replace(/\{(\d+)\}/g, (_, n) => obtenerTexto(coincidencia[Number(n)], elegido));
  }
  return texto;
}

export function formatearTexto(texto, valores) {
  return texto.replace(/\{(\w+)\}/g, (original, clave) => valores[clave] ?? original);
}
